#!/usr/bin/env python3
"""Regenerates index.md and checks the wiki. Run it after every change.

    python3 scripts/wiki.py

ERROR   = must be fixed (the command exits with code 1 while any remain).
WARNING = tell the person; fix it if it makes sense.

Stdlib only, Python 3.8+. The only file this script writes is index.md.
"""
from __future__ import annotations

import datetime as dt
import re
import sys
import unicodedata
from collections import defaultdict
from pathlib import Path

VAULT = Path(__file__).resolve().parent.parent
FOLDERS = {"wiki": "page", "sources": "source", "notes": "note"}
REQUIRED = {
    "page": ["summary", "updated"],
    "source": ["summary", "origin", "ingested"],
    "note": ["summary", "date"],
}
DATE_FIELDS = ("updated", "ingested", "date")
SUMMARY_MAX = 200
PAGE_LINES_MAX = 200
INDEX_LINES_MAX = 200
NO_LINK_CHECK = {"CLAUDE.md", "log.md", "index.md"}  # the log keeps history; the index is generated

LINK_RE = re.compile(r"!?\[\[([^\]\n]+?)\]\]")
FENCE_RE = re.compile(r"^(```|~~~).*?^\1[^\n]*$", re.S | re.M)
INLINE_CODE_RE = re.compile(r"`[^`\n]*`")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
LOG_RE = re.compile(r"^- (\d{4}-\d{2}-\d{2}) ", re.M)
TASK_RE = re.compile(r"^\s*- \[ \] (.*?)\(due: (\d{4}-\d{2}-\d{2})\)", re.M)


def nfc(s: str) -> str:
    """macOS stores file names in NFD; page text is usually NFC."""
    return unicodedata.normalize("NFC", s)


def split_frontmatter(text: str):
    if not text.startswith("---\n"):
        return None, text
    end = text.find("\n---", 4)
    if end == -1:
        return None, text
    return text[4:end], text[end + 4:]


def parse_scalar(v: str):
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        return v[1:-1]
    if v.startswith("[") and v.endswith("]"):
        inner = v[1:-1].strip()
        if not inner:
            return []
        return [parse_scalar(x) for x in re.split(r",\s*(?=(?:[^\"]*\"[^\"]*\")*[^\"]*$)", inner)]
    return v


def parse_frontmatter(raw: str) -> dict:
    """The YAML subset used here: `key: value`, inline lists and block lists."""
    out: dict = {}
    key = None
    for line in raw.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if m:
            key, val = m.group(1), m.group(2)
            out[key] = parse_scalar(val) if val.strip() else None
        elif key and re.match(r"^\s*-\s+", line):
            if not isinstance(out.get(key), list):
                out[key] = []
            out[key].append(parse_scalar(re.sub(r"^\s*-\s+", "", line)))
    return out


def link_targets(text: str) -> list:
    text = INLINE_CODE_RE.sub("", FENCE_RE.sub("", text))
    out = []
    for m in LINK_RE.finditer(text):
        t = m.group(1).split("|")[0].split("#")[0].rstrip("\\").strip()
        if t:
            out.append(nfc(t))
    return out


def skipped(rel: Path) -> bool:
    return any(part.startswith(".") or ".bak." in part for part in rel.parts)


def one_line(s) -> str:
    return re.sub(r"\s+", " ", str(s or "")).strip()


def render_index(pages: list) -> str:
    def of(typ, key, reverse=False):
        return sorted((p for p in pages if p["type"] == typ), key=key, reverse=reverse)

    def line(p, date_field=None):
        date = p["fm"].get(date_field) if date_field else None
        desc = one_line(p["fm"].get("summary"))
        return "- " + (f"{date} " if date else "") + f"[[{p['name']}]]" + (f" — {desc}" if desc else "")

    by_name = lambda p: p["name"].lower()
    paginas = of("page", by_name)
    notas = of("note", lambda p: (str(p["fm"].get("date") or ""), by_name(p)), reverse=True)
    fontes = of("source", lambda p: (str(p["fm"].get("ingested") or ""), by_name(p)), reverse=True)
    out = [
        "---", "type: sistema",
        'summary: "Map of the wiki, generated by scripts/wiki.py from each page\'s summary."',
        "---", "", "# index", "",
        "> Generated. Do not edit: change the page's `summary` and run `python3 scripts/wiki.py`.",
        "> Tasks: [[Tasks]] · History: [[log]] · How to use: [[Guide]]", "",
        f"## Pages ({len(paginas)})", *[line(p) for p in paginas], "",
        f"## Notes ({len(notas)})", *[line(p, "date") for p in notas], "",
        f"## Sources ({len(fontes)})", *[line(p, "ingested") for p in fontes], "",
    ]
    return "\n".join(out)


def main() -> int:
    today = dt.date.today()
    erros, avisos = [], []

    files = [p for p in VAULT.rglob("*") if p.is_file() and not skipped(p.relative_to(VAULT))]
    md = sorted(p for p in files if p.suffix == ".md")

    # A link resolves as in Obsidian: by file name or by path, with or without .md.
    names = defaultdict(list)
    for p in files:
        rel = p.relative_to(VAULT)
        keys = {rel.as_posix(), p.name}
        if p.suffix == ".md":
            keys |= {p.stem, rel.with_suffix("").as_posix()}
        for k in keys:
            names[nfc(k).lower()].append(p)
    if not names.get("index"):  # index.md is written at the end of this run
        names["index"].append(VAULT / "index.md")

    texts = {p: p.read_text(encoding="utf-8", errors="replace") for p in md}
    pages = []
    inbound = defaultdict(set)

    for p in md:
        rel = p.relative_to(VAULT)
        srel = nfc(rel.as_posix())
        top = rel.parts[0]
        if top in {"raw", "scripts"}:
            continue
        text = texts[p]
        raw_fm, _ = split_frontmatter(text)
        fm = parse_frontmatter(raw_fm) if raw_fm is not None else None

        if rel.name not in NO_LINK_CHECK:
            for t in link_targets(text):
                hit = names.get(t.lower())
                if not hit:
                    erros.append(f"{srel}: the link [[{t}]] points to nothing → create the page or remove the link")
                for h in hit or []:
                    if h != p:
                        inbound[h].add(p)

        if top not in FOLDERS:
            continue
        typ = FOLDERS[top]
        if fm is None:
            erros.append(f"{srel}: no frontmatter → line 1 must be `---` (model in CLAUDE.md)")
            continue
        raw_fm = raw_fm or ""
        pages.append({"path": p, "rel": srel, "name": nfc(p.stem), "type": typ, "fm": fm})
        if fm.get("type") != typ:
            erros.append(f"{srel}: `type: {fm.get('type')}` → in {top}/ it must be `type: {typ}`")
        missing = [k for k in REQUIRED[typ] if fm.get(k) in (None, "", [])]
        if missing:
            erros.append(f"{srel}: fill in {', '.join(missing)} in the frontmatter")
        for field in DATE_FIELDS:
            v = fm.get(field)
            if v not in (None, "") and not DATE_RE.match(str(v)):
                erros.append(f"{srel}: `{field}: {v}` → write the date as YYYY-MM-DD")
            elif field != "date" and str(v or "") > today.isoformat():
                erros.append(f"{srel}: `{field}: {v}` is in the future → today is {today}")
        unquoted = re.search(r"^[\w-]+:\s*\[\[", raw_fm, re.M) or re.search(r"^\s*-\s+\[\[", raw_fm, re.M)
        if unquoted:
            erros.append(f"{srel}: unquoted link in the frontmatter → write \"[[Name]]\"")
        summary = one_line(fm.get("summary"))
        if len(summary) > SUMMARY_MAX:
            erros.append(f"{srel}: summary has {len(summary)} characters → cut it to one sentence of at most {SUMMARY_MAX}")
        if typ == "page":
            sources = fm.get("sources")
            sources = [sources] if isinstance(sources, str) else (sources or [])
            if not sources:
                avisos.append(f"{srel}: `sources` is empty → where did this page come from?")
            for s in [] if unquoted else sources:
                if not LINK_RE.search(str(s)):
                    erros.append(f"{srel}: `sources` item is not a link ({s}) → use \"[[Name of a source or note]]\"")
        if typ == "source":
            origin = str(fm.get("origin") or "")
            if origin.startswith("raw/") and not (VAULT / origin).exists() and not (VAULT / nfc(origin)).exists():
                if nfc(origin).lower() not in names:
                    erros.append(f"{srel}: `origin: {origin}` → that file does not exist in raw/")
        if text.count("\n") + 1 > PAGE_LINES_MAX:
            avisos.append(f"{srel}: {text.count(chr(10)) + 1} lines → split it into smaller pages")

    # Repeated names make a [[link]] ambiguous.
    seen = defaultdict(list)
    for pg in pages:
        seen[pg["name"].lower()].append(pg["rel"])
    for rels in seen.values():
        if len(rels) > 1:
            erros.append(f"{' and '.join(sorted(rels))}: same file name → merge into one page or rename")

    system = {VAULT / "index.md", VAULT / "log.md"}
    for pg in pages:
        refs = inbound[pg["path"]] - system
        if pg["type"] == "page" and not refs:
            avisos.append(f"{pg['rel']}: no other page links here → link it from a related page")
        if pg["type"] == "source" and not refs:
            avisos.append(f"{pg['rel']}: no page uses this source → cite it in `sources` or in a page's text")

    # A raw/ file that no page mentions has not been ingested yet.
    outside_raw = [nfc(t) for p, t in texts.items() if p.relative_to(VAULT).parts[0] != "raw"]
    for p in files:
        rel = p.relative_to(VAULT)
        if rel.parts[0] == "raw" and not any(nfc(p.stem) in t for t in outside_raw):
            avisos.append(f"{nfc(rel.as_posix())}: not ingested yet (no page mentions it)")

    # The log must keep up with the latest change.
    log_path = VAULT / "log.md"
    log_dates = LOG_RE.findall(log_path.read_text(encoding="utf-8")) if log_path.exists() else []
    changed = [str(pg["fm"].get(f)) for pg in pages for f in ("updated", "ingested")
               if DATE_RE.match(str(pg["fm"].get(f) or "")) and str(pg["fm"].get(f)) <= today.isoformat()]
    if not log_path.exists():
        erros.append("log.md: missing → create it with a line `- YYYY-MM-DD op: description`")
    elif changed and (not log_dates or max(changed) > max(log_dates)):
        erros.append(f"log.md: a page changed on {max(changed)} and no log line has that date → "
                     f"add on top `- {max(changed)} op: description`")

    tasks = VAULT / "Tasks.md"
    if tasks.exists():
        for what, due in TASK_RE.findall(texts.get(tasks, "")):
            if due < today.isoformat():
                avisos.append(f"Tasks.md: overdue since {due}: {one_line(what)}")

    index_path = VAULT / "index.md"
    index = render_index(pages)
    if index.count("\n") + 1 > INDEX_LINES_MAX:
        avisos.append(f"index.md: {index.count(chr(10)) + 1} lines → the wiki has grown; tell the person it needs reorganizing")
    index_changed = not index_path.exists() or index_path.read_text(encoding="utf-8") != index
    if index_changed:
        index_path.write_text(index, encoding="utf-8")

    count = lambda t: sum(1 for pg in pages if pg["type"] == t)
    print(f"wiki.py {today} · {count('page')} pages · {count('note')} notes · {count('source')} sources")
    print("index.md: " + ("regenerated" if index_changed else "unchanged"))
    for e in erros:
        print("ERROR   " + e)
    for a in avisos:
        print("WARNING " + a)
    if erros:
        print(f"Result: {len(erros)} error(s), {len(avisos)} warning(s). Fix the errors and run it again.")
        return 1
    print(f"Result: OK, 0 errors, {len(avisos)} warning(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
